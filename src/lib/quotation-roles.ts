/**
 * TO-31 — مصدر واحد لصلاحية **الحالة التجارية** لعرض السعر.
 *
 * لماذا ملف مستقل: القائمة يحتاجها السيرفر (`lib/pricing/actions.ts`) والواجهة
 * (`quotation-detail.tsx`) معًا. ملف `"use server"` لا يُصدِّر إلا دوالّ async،
 * فلا يمكن استيراد الثابت منه — والنسخة الثانية في الواجهة هي بالضبط ما أنتج
 * الانحراف الذي تصلحه TO-31: الحارس يسمح لدور، والواجهة تُظهره لدور آخر.
 *
 * القرار النافذ (المالك): **الحالة التجارية (مُرسل/معتمد/منتهي) شغل المبيعات
 * لا المكتب الفني.** المهندس عنده بوابتاه: الاعتماد المبدئي (TO-24) والمراجعة
 * الفنية (`reviewStatus`) — وكلتاهما خارج هذه القائمة.
 *
 * ⚠️ لا تخلط بينها وبين `TecJobStatus` (حالة **الطلب** في شاشة المكتب الفني):
 * تلك كيان آخر (`QuotationRequest`) وشغل المهندس المشروع، ولا تمسّها هذه القائمة.
 */
export const QUOTATION_STATUS_ROLES = ["ADMIN", "SALES_MANAGER"] as const;

// 🔴 TO-31 — مَن سُحب ولماذا (القائمة أعلاه هي الحدّ النهائي: المبيعات والإدارة فقط):
//
// · `TECHNICAL_OFFICE` — كان يكتب `status` و`approvedById` عند APPROVED بلا فحص
//   مسار ولا ملكية ⇒ أي مهندس يعتمد أي عرض في الشركة بمعرفة معرّفه.
//   مُتحقَّق من ActivityLog: **صفر استعمال فعلي** منه (ADMIN 3 · SALES_MANAGER 2).
//
// · `TEC_APPROVER` — سُحب لسببين:
//   (١) الأداة تكتب `approvedById` **بلا مرور ببوابته** (`QUOTATION_APPROVAL_ROLES`)
//       ⇒ طريق خلفي يفكّ الفصل المبني في TO-01/TO-04. سحبه يشدّه لا يفكّه.
//   (٢) بعد توحيد المصدر كانت الأداة **ستظهر له لأول مرة** (كان مسموحًا له
//       والواجهة تخفيها) — وموجة هدفها التضييق لا يصح أن تفتح قدرة جديدة.
//   ⚠️ لا يخسر شيئًا من عمله الحقيقي: الاعتماد الفني (`QUOTATION_APPROVAL_ROLES`)
//   وإصدار أمر التصنيع وبوابة الاعتماد المبدئي كلها خارج هذه القائمة.

export function canChangeQuotationStatus(role: string): boolean {
  return (QUOTATION_STATUS_ROLES as readonly string[]).includes(role);
}

