/**
 * 🔴 SCR-INS-I (موجة C2-fix) — **المصدر الوحيد لتصنيف حالات المعاينة.**
 *
 * ── لماذا ملف مستقل بلا أي استيراد ─────────────────────────────────────────────
 * وضعُ هذه الثوابت في `services/inspections.ts` أنتج **استيرادًا دائريًا**:
 * `inspections.ts` يستورد `recompute*` من `status-derivation.ts`، وهذا الأخير
 * يحتاج التصنيف. الدورة تعمل بالمصادفة ما دام الاستهلاك **داخل الدوال** (وقت
 * النداء يكون الطرفان مُهيَّأين)، وتنكسر صامتةً أول ما يُقرأ الثابت في **مستوى
 * الوحدة** — قيمة `undefined` في شرط أمني، بلا خطأ ولا سجل.
 * ملف أوراق (leaf) بصفر تبعيات يقطع الدورة بنيويًا لا بترتيب حظّ.
 *
 * ── التصنيف ────────────────────────────────────────────────────────────────────
 * الـenum ست قيم (`prisma/schema.prisma`): `REQUESTED · SCHEDULED · POSTPONED ·
 * DONE · OVERDUE · CANCELLED`، وتنقسم إلى ثلاث فئات لا فئتين:
 *
 * 1. **نهائية** (`DONE` · `CANCELLED`) — خارج دورة العمل: لا تُعدّ معلّقة، ولا تُبقي
 *    العميل في مرحلة «معاينة»، ولا تُجدوَل. `DONE` = نُفِّذت · `CANCELLED` = لن تُنفَّذ.
 * 2. **موقوفة مؤقتًا** (`POSTPONED`) — **ليست نهائية عمدًا**: تُستأنف، فتبقى معلّقة
 *    ونشطة وقابلة للجدولة. حجبها كان سيُنتج صفًّا محبوسًا (IN-07/IN-48).
 * 3. **مشتقّة للعرض** (`OVERDUE`) — لا تُكتب في القاعدة إطلاقًا (IN-07).
 */

/**
 * الحالات النهائية. **أي حالة نهائية جديدة تُضاف هنا وحدها.**
 *
 * ⚠️ يستهلكها **سبعة قرّاء** عبر أربعة ملفات (عدّاد المعاينات · داشبورد المبيعات ·
 * حارس الجدولة · `inspectionActive` · `activeInspection` · زر الجدولة · اشتقاق
 * التأخير). سبع نسخ نصّية من قاعدة واحدة = انحراف مؤجَّل بالتعريف — وهي علّة IN-12
 * التي تكرّرت في هذا الموديول ثلاث مرات قبل هذه الموجة.
 *
 * ⚠️ **`as const` لا `readonly string[]`:** التوسيع إلى `string` كان يُسقط اتحاد
 * `InspectionStatus` عند حدّ Prisma (`notIn` يطلب `InspectionStatus[]`) فيلزم `as`
 * لإسكات المترجم — وهو محظور (Definition of Done). بهذا الشكل تُقبل القيم مباشرةً،
 * ويرفض المترجم أي قيمة ليست من الـenum عند أي تعديل مستقبلي.
 */
export const TERMINAL_INSPECTION_STATUSES = ["DONE", "CANCELLED"] as const;

/**
 * الحالات التي **لا يُحتسب لها تأخير**.
 *
 * النهائيتان + `POSTPONED`: التأجيل والإلغاء مصدرهما **العميل** (الحقيقة 1 من نصّ
 * حسن · D-IN-20)، فاحتسابهما تأخيرًا يُحمِّل القسمَ قرارَ عميلٍ لا يملكه — ومؤشر
 * SLA المبني على ذلك يقيس شيئًا غير الأداء.
 */
export const NEVER_OVERDUE_STATUSES: readonly string[] = [
  ...TERMINAL_INSPECTION_STATUSES,
  "POSTPONED",
];

/**
 * فحص عضوية يقبل `string` — للمواضع التي تحمل الحالة كنصّ عامّ (DTO الواجهة،
 * `deriveEffectiveStatus` المُعمَّم). يُغني عن `includes` على اتحاد ضيّق يرفض `string`.
 */
export function isTerminalInspectionStatus(status: string): boolean {
  return (TERMINAL_INSPECTION_STATUSES as readonly string[]).includes(status);
}
